export type ActionIconName = keyof typeof ACTION_ICONS

export function navIcon(href: string, fallback: LucideIcon = LayoutDashboard): LucideIcon {
  if (NAV_ICONS[href]) return NAV_ICONS[href]
  const clean = href.split("?")[0].split("#")[0]
  if (NAV_ICONS[clean]) return NAV_ICONS[clean]
  const parts = clean.split("/").filter(Boolean)
  while (parts.length > 2) {
    parts.pop()
    const parent = `/${parts.join("/")}`
    if (NAV_ICONS[parent]) return NAV_ICONS[parent]
  }
  return fallback
}

export function accountsNavIcon(groupId: string): LucideIcon {
  return ACCOUNTS_NAV_ICONS[groupId] || BookOpen
}

